/* Convert snake_case to camelCase for function naming */
static char *sql_fn_name(const char *name) {
    if (!name) return strdup("unknown");
    /* Prefix with resolve_ if not already present */
    const char *prefix = "resolve_";
    if (strncmp(name, "resolve_", 8) == 0) {
        return strdup(name);
    }
    char *out = malloc(strlen(prefix) + strlen(name) + 1);
    sprintf(out, "%s%s", prefix, name);
    return out;
}

static void emit_projection_sql(FILE *out, Decl *d) {
    if (!d->name.text) return;

    char *fn_name = sql_fn_name(d->name.text);

    /* Extract invariant and context field names */
    const char *invariant_name = NULL;
    const char *context_name = NULL;
    const char *yields_name = NULL;
    (void)yields_name;  /* reserved for future use */

    for (size_t i = 0; i < d->as.projection.field_count; i++) {
        DeclField *f = &d->as.projection.fields[i];
        if (!f->label.text) continue;
        if (strcmp(f->label.text, "invariant") == 0) {
            if (f->value && f->value->type == EXPR_IDENT)
                invariant_name = f->value->as.ident.name;
        }
        if (strcmp(f->label.text, "context") == 0) {
            if (f->value && f->value->type == EXPR_IDENT)
                context_name = f->value->as.ident.name;
        }
        if (strcmp(f->label.text, "yields") == 0) {
            if (f->value && f->value->type == EXPR_IDENT)
                yields_name = f->value->as.ident.name;
        }
    }

    fprintf(out, "-- projection %s\n", d->name.text);
    fprintf(out, "CREATE OR REPLACE FUNCTION %s(\n", fn_name);
    fprintf(out, "  p_%s text", invariant_name ? invariant_name : "invariant");
    if (context_name) {
        fprintf(out, ",\n  p_%s text", context_name);
    }
    fprintf(out, "\n) RETURNS text\n");
    fprintf(out, "  LANGUAGE sql\n  IMMUTABLE\nAS $$\n");
    fprintf(out, "  SELECT CASE\n");

    /* Emit case arms */
    for (size_t a = 0; a < d->as.projection.arm_count; a++) {
        ProjectionArm *arm = &d->as.projection.arms[a];
        if (!arm->pattern || !arm->body) continue;

        /* Extract pattern values */
        const char *p1 = NULL, *p2 = NULL;
        if (arm->pattern->type == EXPR_LIST && arm->pattern->as.list.count >= 2) {
            Expr *e1 = arm->pattern->as.list.items[0];
            Expr *e2 = arm->pattern->as.list.items[1];
            if (e1->type == EXPR_IDENT) p1 = e1->as.ident.name;
            if (e1->type == EXPR_WILDCARD) p1 = "_";
            if (e2->type == EXPR_IDENT) p2 = e2->as.ident.name;
            if (e2->type == EXPR_WILDCARD) p2 = "_";
        } else if (arm->pattern->type == EXPR_WILDCARD) {
            p1 = "_"; p2 = "_";
        }

        /* Extract body value */
        const char *result = NULL;
        if (arm->body->type == EXPR_STRING)
            result = arm->body->as.string.value;

        if (!p1 || !result) continue;

        /* Wildcard (_, _) → ELSE */
        if (strcmp(p1, "_") == 0 && p2 && strcmp(p2, "_") == 0) {
            fprintf(out, "    ELSE '%s'\n", result);
            continue;
        }

        /* Build WHEN conditions */
        fprintf(out, "    WHEN ");
        int need_and = 0;
        if (strcmp(p1, "_") != 0) {
            fprintf(out, "p_%s = '%s'", invariant_name ? invariant_name : "invariant", p1);
            need_and = 1;
        }
        if (p2 && strcmp(p2, "_") != 0) {
            if (need_and) fprintf(out, " AND ");
            fprintf(out, "p_%s = '%s'", context_name ? context_name : "context", p2);
        }
        fprintf(out, " THEN '%s'\n", result);
    }

    /* Default fallback if no wildcard arm */
    fprintf(out, "  END\n$$;\n\n");

    free(fn_name);
}

