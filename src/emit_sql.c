/* ------------------------------------------------------------ */

/* Convert meihua expressions to SQL math — mirrors meihua_expr_to_ts */
static char *meihua_expr_to_sql(Expr *e) {
    if (!e) return strdup("0");

    switch (e->type) {
    case EXPR_CALL: {
        if (!e->as.call.callee) return strdup("0");
        const char *callee = e->as.call.callee;
        /* M5: map math functions via generated enum lookup */
        math_fn_t mfn = math_fn_from_name(callee);
        const char *sql_fn = (mfn != (math_fn_t)-1) ? math_fn_sql(mfn) : NULL;

        /* log2 special case: log2(x) → log(2, x) in PostgreSQL */
        if (mfn == MATH_FN_LOG2 && e->as.call.arg_count == 1) {
            char *arg = meihua_expr_to_sql(e->as.call.args[0]);
            char *buf = malloc(strlen(arg) + 16);
            sprintf(buf, "log(2, %s)", arg);
            free(arg);
            return buf;
        }

        const char *fn = sql_fn ? sql_fn : callee;
        size_t total_len = strlen(fn) + 3;
        char **arg_strs = malloc(e->as.call.arg_count * sizeof(char *));
        for (size_t i = 0; i < e->as.call.arg_count; i++) {
            arg_strs[i] = meihua_expr_to_sql(e->as.call.args[i]);
            total_len += strlen(arg_strs[i]) + 2;
        }
        char *buf = malloc(total_len + 1);
        int pos = sprintf(buf, "%s(", fn);
        for (size_t i = 0; i < e->as.call.arg_count; i++) {
            if (i > 0) pos += sprintf(buf + pos, ", ");
            pos += sprintf(buf + pos, "%s", arg_strs[i]);
            free(arg_strs[i]);
        }
        sprintf(buf + pos, ")");
        free(arg_strs);
        return buf;
    }
    case EXPR_BINARY: {
        char *left = meihua_expr_to_sql(e->as.binary.left);
        char *right = meihua_expr_to_sql(e->as.binary.right);
        const char *op = e->as.binary.op ? e->as.binary.op : "+";
        if (strcmp(op, "^") == 0) {
            char *buf = malloc(strlen(left) + strlen(right) + 16);
            sprintf(buf, "pow(%s, %s)", left, right);
            free(left); free(right);
            return buf;
        }
        /* SQL operator mapping: == → =, != → <> */
        const char *sql_op = op;
        if (strcmp(op, "==") == 0) sql_op = "=";
        else if (strcmp(op, "!=") == 0) sql_op = "<>";
        char *buf = malloc(strlen(left) + strlen(right) + strlen(sql_op) + 8);
        sprintf(buf, "(%s %s %s)", left, sql_op, right);
        free(left); free(right);
        return buf;
    }
    case EXPR_IDENT:
        if (e->as.ident.name) {
            /* Prefix identifiers with p_ for function parameters */
            char *buf = malloc(strlen(e->as.ident.name) + 3);
            sprintf(buf, "p_%s", e->as.ident.name);
            return buf;
        }
        return strdup("0");
    case EXPR_NUMBER:
        if (e->as.number.text) return strdup(e->as.number.text);
        return strdup("0");
    case EXPR_UNARY: {
        char *operand = meihua_expr_to_sql(e->as.unary.operand);
        const char *op = e->as.unary.op ? e->as.unary.op : "-";
        char *buf = malloc(strlen(operand) + strlen(op) + 4);
        sprintf(buf, "(%s%s)", op, operand);
        free(operand);
        return buf;
    }
    case EXPR_IF: {
        char *cond = meihua_expr_to_sql(e->as.if_expr.condition);
        char *then_b = meihua_expr_to_sql(e->as.if_expr.then_branch);
        char *else_b = meihua_expr_to_sql(e->as.if_expr.else_branch);
        char *buf = malloc(strlen(cond) + strlen(then_b) + strlen(else_b) + 40);
        sprintf(buf, "CASE WHEN %s THEN %s ELSE %s END", cond, then_b, else_b);
        free(cond); free(then_b); free(else_b);
        return buf;
    }
    case EXPR_COALESCE: {
        char *left = meihua_expr_to_sql(e->as.coalesce.left);
        char *right = meihua_expr_to_sql(e->as.coalesce.right);
        char *buf = malloc(strlen(left) + strlen(right) + 16);
        sprintf(buf, "COALESCE(%s, %s)", left, right);
        free(left); free(right);
        return buf;
    }
    case EXPR_STRING: {
        const char *val = e->as.string.value ? e->as.string.value : "";
        char *buf = malloc(strlen(val) + 4);
        sprintf(buf, "'%s'", val);
        return buf;
    }
    case EXPR_LIST: {
        size_t total = 8; /* ARRAY[] */
        char **items = malloc(e->as.list.count * sizeof(char *));
        for (size_t i = 0; i < e->as.list.count; i++) {
            items[i] = meihua_expr_to_sql(e->as.list.items[i]);
            total += strlen(items[i]) + 2;
        }
        char *buf = malloc(total + 1);
        int pos = sprintf(buf, "ARRAY[");
        for (size_t i = 0; i < e->as.list.count; i++) {
            if (i > 0) pos += sprintf(buf + pos, ", ");
            pos += sprintf(buf + pos, "%s", items[i]);
            free(items[i]);
        }
        sprintf(buf + pos, "]");
        free(items);
        return buf;
    }
    case EXPR_MATCH: {
        /* match discriminant { pat -> body, ... } → CASE disc WHEN pat THEN body ... END */
        char *disc = meihua_expr_to_sql(e->as.match_expr.discriminant);
        size_t total = strlen(disc) + 16; /* CASE ... END */
        char **whens = malloc(e->as.match_expr.arm_count * sizeof(char *));
        for (size_t i = 0; i < e->as.match_expr.arm_count; i++) {
            char *body = meihua_expr_to_sql(e->as.match_expr.arms[i].body);
            Expr *pat = e->as.match_expr.arms[i].pattern;
            if (pat && pat->type == EXPR_WILDCARD) {
                size_t len = strlen(body) + 8;
                whens[i] = malloc(len + 1);
                sprintf(whens[i], " ELSE %s", body);
            } else {
                /* Pattern idents are literal match values, not parameters.
                 * Emit as SQL string literals (not p_-prefixed). */
                char *pstr;
                if (pat && pat->type == EXPR_IDENT && pat->as.ident.name) {
                    pstr = malloc(strlen(pat->as.ident.name) + 4);
                    sprintf(pstr, "'%s'", pat->as.ident.name);
                } else if (pat && pat->type == EXPR_NUMBER && pat->as.number.text) {
                    pstr = strdup(pat->as.number.text);
                } else if (pat && pat->type == EXPR_STRING && pat->as.string.value) {
                    pstr = malloc(strlen(pat->as.string.value) + 4);
                    sprintf(pstr, "'%s'", pat->as.string.value);
                } else {
                    pstr = meihua_expr_to_sql(pat);
                }
                size_t len = strlen(pstr) + strlen(body) + 16;
                whens[i] = malloc(len + 1);
                sprintf(whens[i], " WHEN %s THEN %s", pstr, body);
                free(pstr);
            }
            total += strlen(whens[i]);
            free(body);
        }
        char *buf = malloc(total + 1);
        int pos = sprintf(buf, "CASE %s", disc);
        for (size_t i = 0; i < e->as.match_expr.arm_count; i++) {
            pos += sprintf(buf + pos, "%s", whens[i]);
            free(whens[i]);
        }
        sprintf(buf + pos, " END");
        free(whens);
        free(disc);
        return buf;
    }
    default:
        return strdup("/* expr */");
    }
}

static void emit_meihua_sql(FILE *out, Decl *d) {
    if (!d->name.text) return;

    fprintf(out, "-- meihua %s — pure computation\n", d->name.text);
    fprintf(out, "CREATE OR REPLACE FUNCTION %s(\n", d->name.text);

    for (size_t i = 0; i < d->as.exec_layer.param_count; i++) {
        if (d->as.exec_layer.params[i].text) {
            fprintf(out, "  p_%s double precision", d->as.exec_layer.params[i].text);
            if (i + 1 < d->as.exec_layer.param_count) fprintf(out, ",\n");
        }
    }

    fprintf(out, "\n) RETURNS double precision\n");
    fprintf(out, "  LANGUAGE sql\n  IMMUTABLE\n");
    fprintf(out, "AS $$\n");

    Expr *body = d->as.exec_layer.body;
    /* Unwrap single-statement blocks */
    if (body && body->type == EXPR_BLOCK && body->as.block.count == 1) {
        body = body->as.block.stmts[0];
    }
    if (body) {
        char *sql = meihua_expr_to_sql(body);
        fprintf(out, "  SELECT %s\n", sql);
        free(sql);
    } else {
        fprintf(out, "  SELECT 0 -- no body captured\n");
    }

    fprintf(out, "$$;\n\n");
}

