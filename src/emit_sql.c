/* morphism → SQL function stub                                  */
/* ------------------------------------------------------------ */

static void emit_morphism_sql(FILE *out, Decl *d) {
    if (!d->name.text) return;

    const char *from_name = NULL;
    const char *to_name = NULL;
    if (d->as.morphism.signature && d->as.morphism.signature->type == EXPR_ARROW) {
        Expr *rel = d->as.morphism.signature;
        if (rel->as.arrow.from && rel->as.arrow.from->type == EXPR_IDENT)
            from_name = rel->as.arrow.from->as.ident.name;
        if (rel->as.arrow.to && rel->as.arrow.to->type == EXPR_IDENT)
            to_name = rel->as.arrow.to->as.ident.name;
    }

    fprintf(out, "-- morphism %s : %s -> %s\n",
            d->name.text,
            from_name ? from_name : "?",
            to_name ? to_name : "?");
    fprintf(out, "-- TODO: Implement as SECURITY DEFINER function\n");
    fprintf(out, "-- CREATE OR REPLACE FUNCTION %s(p_user_id uuid, p_resource_id bigint)\n",
            d->name.text);
    fprintf(out, "-- RETURNS void LANGUAGE plpgsql SECURITY DEFINER AS $$\n");
    fprintf(out, "-- BEGIN\n");
    fprintf(out, "--   UPDATE memberships SET structural_role = '%s'\n",
            to_name ? to_name : "?");
    fprintf(out, "--   WHERE user_id = p_user_id AND resource_id = p_resource_id\n");
    fprintf(out, "--     AND structural_role = '%s';\n", from_name ? from_name : "?");
    fprintf(out, "-- END;\n-- $$;\n\n");
}

