/*
 * suhc — emit_sql.c
 * SQL (PostgreSQL) code generation from .szh declarations.
 *
 * Only dependency declarations produce SQL output.
 * The emitted schema matches the Spoxis migration conventions:
 *   - YYYYMMDDHHMMSS_description.sql naming
 *   - IF NOT EXISTS on index creation
 *   - timestamptz for moments, date for calendar constraints
 *   - RLS policies emitted as comments (manual review required)
 */

