/* Simple snake_case to snake_case SQL identifier conversion */
static char *sql_param_name(const char *label) {
    if (!label) return strdup("p_unknown");
    char *out = malloc(strlen(label) + 3);
    sprintf(out, "p_%s", label);
    return out;
}

/* Convert an Expr to a SQL-ish string (simplified, for comments and
 * simple expressions). Full SQL expression compilation is Phase 2B. */
static char *expr_to_sql_str(Expr *e) {
    if (!e) return strdup("NULL");
    switch (e->type) {
    case EXPR_IDENT:
        return e->as.ident.name ? strdup(e->as.ident.name) : strdup("?");
    case EXPR_STRING: {
        char *buf = malloc(strlen(e->as.string.value ? e->as.string.value : "") + 4);
        sprintf(buf, "'%s'", e->as.string.value ? e->as.string.value : "");
        return buf;
    }
    case EXPR_CALL: {
        if (!e->as.call.callee) return strdup("unknown()");
        char *buf = malloc(256);
        int pos = sprintf(buf, "%s(", e->as.call.callee);
        for (size_t i = 0; i < e->as.call.arg_count && pos < 240; i++) {
            if (i > 0) pos += sprintf(buf + pos, ", ");
            char *arg = expr_to_sql_str(e->as.call.args[i]);
            pos += sprintf(buf + pos, "%s", arg);
            free(arg);
        }
        pos += sprintf(buf + pos, ")");
        return buf;
    }
    case EXPR_PIPE_CHAIN: {
        if (e->as.pipe_chain.count == 0) return strdup("NULL");
        /* Emit as nested calls: a |> b |> c → c(b(a)) */
        char *result = expr_to_sql_str(e->as.pipe_chain.stages[0]);
        for (size_t i = 1; i < e->as.pipe_chain.count; i++) {
            char *fn = expr_to_sql_str(e->as.pipe_chain.stages[i]);
            char *buf = malloc(strlen(fn) + strlen(result) + 4);
            sprintf(buf, "%s(%s)", fn, result);
            free(fn); free(result);
            result = buf;
        }
        return result;
    }
    default:
        return strdup("/* expr */");
    }
}

static void emit_traversal_sql(FILE *out, Decl *d) {
    if (!d->name.text) return;

    char *fn_name = sql_fn_name(d->name.text);

    /* Collect section labels and bodies */
    const char *xi_label = NULL, *zeta_label = NULL, *x_label = NULL;
    const char *omega_label = NULL, *delta_label = NULL;
    Expr *rk_expr = NULL, *zeta_expr = NULL, *x_expr = NULL;

    for (size_t i = 0; i < d->as.traversal.section_count; i++) {
        TraversalSection *sec = &d->as.traversal.sections[i];
        switch (sec->section_kind) {
        case KIND_XI:       xi_label = sec->label.text; break;
        case KIND_ZETA:     zeta_label = sec->label.text; zeta_expr = sec->body; break;
        case KIND_X:        x_label = sec->label.text; x_expr = sec->body; break;
        case KIND_RK:       rk_expr = sec->body; break;
        case KIND_OMEGA:    omega_label = sec->label.text; break;
        case KIND_DELTA_RK: delta_label = sec->label.text; break;
        default: break;
        }
    }
    (void)zeta_expr; (void)x_expr;

    /* Header comment */
    fprintf(out, "-- traversal %s\n", d->name.text);
    fprintf(out, "-- Pipeline: %s (ξ)",
            xi_label ? xi_label : "?");
    if (zeta_label) fprintf(out, " × %s (ζ)", zeta_label);
    fprintf(out, " → %s (ω)", omega_label ? omega_label : "?");
    if (delta_label) fprintf(out, " | cast: %s (ΔR.k)", delta_label);
    fprintf(out, "\n");

    fprintf(out, "CREATE OR REPLACE FUNCTION %s(\n", fn_name);

    /* Parameters from section labels */
    bool first_param = true;
    if (xi_label) {
        char *pname = sql_param_name(xi_label);
        fprintf(out, "  %s uuid", pname);
        free(pname);
        first_param = false;
    }
    if (zeta_label) {
        char *pname = sql_param_name(zeta_label);
        fprintf(out, "%s\n  %s text", first_param ? "" : ",", pname);
        free(pname);
        first_param = false;
    }
    if (x_label) {
        char *pname = sql_param_name(x_label);
        fprintf(out, "%s\n  %s bigint[] DEFAULT '{}'", first_param ? "" : ",", pname);
        free(pname);
    }

    fprintf(out, "\n) RETURNS jsonb\n");
    fprintf(out, "  LANGUAGE plpgsql\n  STABLE\n");
    fprintf(out, "AS $$\n");
    fprintf(out, "DECLARE\n  v_result jsonb;\nBEGIN\n");

    /* R.k operator body → CASE statement */
    if (rk_expr && rk_expr->type == EXPR_MATCH) {
        char *disc = rk_expr->as.match_expr.discriminant ?
            strdup(rk_expr->as.match_expr.discriminant->as.ident.name) :
            strdup("?");
        char *pname = sql_param_name(disc);

        fprintf(out, "  CASE %s\n", pname);
        for (size_t a = 0; a < rk_expr->as.match_expr.arm_count; a++) {
            Expr *pat = rk_expr->as.match_expr.arms[a].pattern;
            Expr *body = rk_expr->as.match_expr.arms[a].body;
            char *body_str = body ? expr_to_sql_str(body) : strdup("NULL");

            if (pat && pat->type == EXPR_WILDCARD) {
                fprintf(out, "    ELSE\n");
                fprintf(out, "      -- %s\n", body_str);
                fprintf(out, "      v_result := '[]'::jsonb;\n");
            } else {
                char *pat_str = pat ? expr_to_sql_str(pat) : strdup("?");
                fprintf(out, "    WHEN '%s' THEN\n", pat_str);
                fprintf(out, "      -- %s\n", body_str);
                fprintf(out, "      v_result := '[]'::jsonb; -- TODO: implement\n");
                free(pat_str);
            }
            free(body_str);
        }
        fprintf(out, "  END CASE;\n");
        free(disc);
        free(pname);
    } else if (rk_expr) {
        char *body_str = expr_to_sql_str(rk_expr);
        fprintf(out, "  -- R.k: %s\n", body_str);
        fprintf(out, "  v_result := '[]'::jsonb; -- TODO: implement\n");
        free(body_str);
    } else {
        fprintf(out, "  v_result := '[]'::jsonb;\n");
    }

    fprintf(out, "  RETURN COALESCE(v_result, '[]'::jsonb);\n");
    fprintf(out, "END;\n$$;\n\n");

    free(fn_name);
}

