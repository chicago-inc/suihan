/* Collect enum values from ξ declarations for CHECK constraints */
typedef struct {
    char  *name;
    char **values;
    size_t count;
} EnumDef;

typedef struct {
    EnumDef *defs;
    size_t   count;
    size_t   capacity;
} EnumRegistry;

static void er_init(EnumRegistry *er) {
    er->capacity = 16;
    er->defs = calloc(er->capacity, sizeof(EnumDef));
    er->count = 0;
}

static void er_free(EnumRegistry *er) {
    for (size_t i = 0; i < er->count; i++) {
        free(er->defs[i].name);
        for (size_t j = 0; j < er->defs[i].count; j++)
            free(er->defs[i].values[j]);
        free(er->defs[i].values);
    }
    free(er->defs);
}

static void er_add(EnumRegistry *er, const char *name, Expr *val) {
    if (!val || val->type != EXPR_ENUM) return;
    if (er->count >= er->capacity) {
        er->capacity *= 2;
        er->defs = realloc(er->defs, er->capacity * sizeof(EnumDef));
    }
    EnumDef *ed = &er->defs[er->count++];
    ed->name = strdup(name);
    ed->count = val->as.enumeration.count;
    ed->values = malloc(ed->count * sizeof(char *));
    for (size_t i = 0; i < ed->count; i++) {
        ed->values[i] = val->as.enumeration.items[i].name.text ?
            strdup(val->as.enumeration.items[i].name.text) : strdup("");
    }
}

static EnumDef *er_find(EnumRegistry *er, const char *name) {
    for (size_t i = 0; i < er->count; i++) {
        if (strcmp(er->defs[i].name, name) == 0) return &er->defs[i];
    }
    return NULL;
}

/* ------------------------------------------------------------ */
/* dependency → CREATE TABLE                                     */
/* ------------------------------------------------------------ */

static void emit_dependency_sql(FILE *out, Decl *d, EnumRegistry *er) {
    if (!d->name.text) return;

    char *table_name = pluralize(d->name.text);

    /* Extract from/to from arrow expression */
    const char *from_name = NULL;
    const char *to_name = NULL;
    if (d->as.dependency.relation && d->as.dependency.relation->type == EXPR_ARROW) {
        Expr *rel = d->as.dependency.relation;
        if (rel->as.arrow.from && rel->as.arrow.from->type == EXPR_IDENT)
            from_name = rel->as.arrow.from->as.ident.name;
        if (rel->as.arrow.to && rel->as.arrow.to->type == EXPR_IDENT)
            to_name = rel->as.arrow.to->as.ident.name;
    }

    fprintf(out, "-- dependency %s : %s -> %s\n",
            d->name.text,
            from_name ? from_name : "?",
            to_name ? to_name : "?");
    fprintf(out, "CREATE TABLE IF NOT EXISTS %s (\n", table_name);
    fprintf(out, "  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY");

    /* FK for 'from' side */
    if (from_name) {
        if (strcmp(from_name, "user") == 0) {
            fprintf(out, ",\n  user_id uuid NOT NULL REFERENCES profiles(id)");
        } else {
            char *plural = pluralize(from_name);
            fprintf(out, ",\n  %s_id bigint NOT NULL REFERENCES %s(id)", from_name, plural);
            free(plural);
        }
    }

    /* FK for 'to' side */
    if (to_name) {
        if (strcmp(to_name, "user") == 0) {
            fprintf(out, ",\n  target_user_id uuid NOT NULL REFERENCES profiles(id)");
        } else {
            char *plural = pluralize(to_name);
            fprintf(out, ",\n  %s_id bigint NOT NULL REFERENCES %s(id)", to_name, plural);
            free(plural);
        }
    }

    /* Columns from 'carries' field */
    for (size_t i = 0; i < d->as.dependency.field_count; i++) {
        DeclField *f = &d->as.dependency.fields[i];
        if (!f->label.text || strcmp(f->label.text, "carries") != 0) continue;
        if (!f->value) continue;

        /* Handle single ident or list */
        const char *carry_names[16];
        size_t carry_count = 0;

        if (f->value->type == EXPR_IDENT && f->value->as.ident.name) {
            carry_names[carry_count++] = f->value->as.ident.name;
        } else if (f->value->type == EXPR_LIST) {
            for (size_t j = 0; j < f->value->as.list.count && carry_count < 16; j++) {
                Expr *item = f->value->as.list.items[j];
                if (item && item->type == EXPR_IDENT && item->as.ident.name)
                    carry_names[carry_count++] = item->as.ident.name;
            }
        }

        for (size_t c = 0; c < carry_count; c++) {
            const char *carry = carry_names[c];

            if (strcmp(carry, "permission") == 0) {
                /* structural_role with CHECK constraint */
                EnumDef *role_enum = er_find(er, "structural_role");
                fprintf(out, ",\n  structural_role text NOT NULL DEFAULT 'pending'");
                if (role_enum) {
                    fprintf(out, "\n    CHECK (structural_role IN (");
                    for (size_t v = 0; v < role_enum->count; v++) {
                        fprintf(out, "'%s'", role_enum->values[v]);
                        if (v + 1 < role_enum->count) fprintf(out, ", ");
                    }
                    fprintf(out, "))");
                }
                fprintf(out, ",\n  role_types text[]");
            }
            else if (strcmp(carry, "label") == 0) {
                fprintf(out, ",\n  display_title text");
            }
            else if (strcmp(carry, "participation") == 0) {
                fprintf(out, ",\n  status text NOT NULL DEFAULT 'pending'");
            }
            else {
                fprintf(out, ",\n  %s text", carry);
            }
        }
    }

    fprintf(out, ",\n  created_at timestamptz NOT NULL DEFAULT now()");

    /* UNIQUE constraint for the relationship */
    if (from_name && to_name) {
        const char *from_col = strcmp(from_name, "user") == 0 ? "user_id" : from_name;
        const char *to_col = strcmp(to_name, "user") == 0 ? "target_user_id" : to_name;

        /* Build column name strings for UNIQUE */
        fprintf(out, ",\n  UNIQUE (");
        if (strcmp(from_name, "user") == 0) {
            fprintf(out, "user_id");
        } else {
            fprintf(out, "%s_id", from_col);
        }
        fprintf(out, ", ");
        if (strcmp(to_name, "user") == 0) {
            fprintf(out, "target_user_id");
        } else {
            fprintf(out, "%s_id", to_col);
        }
        fprintf(out, ")");
    }

    fprintf(out, "\n);\n\n");

    /* RLS hint */
    fprintf(out, "-- TODO: Enable RLS and create policies for %s\n", table_name);
    fprintf(out, "-- ALTER TABLE %s ENABLE ROW LEVEL SECURITY;\n\n", table_name);

    free(table_name);
}

/* ------------------------------------------------------------ */
/* dimension → ENUM type (optional)                              */
/* ------------------------------------------------------------ */

static void emit_dimension_sql(FILE *out, Decl *d) {
    if (!d->name.text) return;
    Expr *members = d->as.dimension.members;
    if (!members) return;

    fprintf(out, "-- dimension %s\n", d->name.text);
    fprintf(out, "-- Values:");

    if (members->type == EXPR_LIST) {
        for (size_t i = 0; i < members->as.list.count; i++) {
            Expr *item = members->as.list.items[i];
            if (item && item->type == EXPR_IDENT && item->as.ident.name) {
                fprintf(out, " %s", item->as.ident.name);
            }
        }
    }
    fprintf(out, "\n");
    fprintf(out, "-- (Used as CHECK constraint values, not as a SQL ENUM type.\n");
    fprintf(out, "--  Enums in PostgreSQL cannot be extended without migration.)\n\n");
}

