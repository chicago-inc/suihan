static void emit_songqiao_sql(FILE *out, Decl *d) {
    if (!d->name.text) return;

    fprintf(out, "-- songqiao %s — runtime landscape configuration\n", d->name.text);
    fprintf(out, "CREATE OR REPLACE FUNCTION songqiao_%s(\n", d->name.text);

    for (size_t i = 0; i < d->as.exec_layer.param_count; i++) {
        if (d->as.exec_layer.params[i].text) {
            fprintf(out, "  p_%s text", d->as.exec_layer.params[i].text);
            if (i + 1 < d->as.exec_layer.param_count) fprintf(out, ",\n");
        }
    }

    fprintf(out, "\n) RETURNS jsonb\n");
    fprintf(out, "  LANGUAGE sql\n  IMMUTABLE\n");
    fprintf(out, "AS $$\n");

    Expr *body = d->as.exec_layer.body;
    if (body && body->type == EXPR_BLOCK && body->as.block.count == 1) {
        body = body->as.block.stmts[0];
    }
    if (body) {
        char *sql = meihua_expr_to_sql(body);
        fprintf(out, "  SELECT to_jsonb(%s)\n", sql);
        free(sql);
    } else {
        fprintf(out, "  SELECT '{}'::jsonb\n");
    }

    fprintf(out, "$$;\n\n");
}

