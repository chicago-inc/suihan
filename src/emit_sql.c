static void emit_sql_header(FILE *out, const char *filename) {
    fprintf(out, "-- Generated by suhc (the suihan compiler) from %s\n",
            filename ? filename : "<stdin>");
    fprintf(out, "-- DO NOT EDIT — regenerate from the .szh source.\n");
    fprintf(out, "--\n");
    fprintf(out, "-- Dependencies are emitted as CREATE TABLE statements.\n");
    fprintf(out, "-- Review and adjust column types before running.\n\n");
}

