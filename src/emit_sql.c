static const char *sql_kind_str(Kind k) {
    switch (k) {
    case KIND_XI:       return "xi";
    case KIND_ZETA:     return "zeta";
    case KIND_X:        return "x";
    case KIND_RK:       return "rk";
    case KIND_OMEGA:    return "omega";
    case KIND_DELTA_RK: return "delta_rk";
    case KIND_INFERRED: return "inferred";
    case KIND_NONE:     return "none";
    }
    return "unknown";
}

static void emit_kind_metadata_table(FILE *out, Program *prog) {
    /* Count non-import declarations */
    size_t real_count = 0;
    for (size_t i = 0; i < prog->count; i++) {
        if (prog->decls[i]->type != DECL_IMPORT &&
            prog->decls[i]->name.text)
            real_count++;
    }
    if (real_count == 0) return;

    fprintf(out, "\n-- Kind metadata (256-bit perpendicular encoding)\n");
    fprintf(out, "CREATE TABLE IF NOT EXISTS _szh_kind_metadata (\n");
    fprintf(out, "  symbol_name  text PRIMARY KEY,\n");
    fprintf(out, "  kind         text NOT NULL,\n");
    fprintf(out, "  source_file  text,\n");
    fprintf(out, "  updated_at   timestamptz DEFAULT now()\n");
    fprintf(out, ");\n\n");

    for (size_t i = 0; i < prog->count; i++) {
        Decl *d = prog->decls[i];
        if (d->type == DECL_IMPORT) continue;
        if (!d->name.text) continue;

        fprintf(out,
            "INSERT INTO _szh_kind_metadata (symbol_name, kind, source_file)\n"
            "VALUES ('%s', '%s', '%s')\n"
            "ON CONFLICT (symbol_name) DO UPDATE SET\n"
            "  kind = EXCLUDED.kind,\n"
            "  source_file = EXCLUDED.source_file,\n"
            "  updated_at = now();\n\n",
            d->name.text,
            sql_kind_str(d->kind),
            prog->filename ? prog->filename : "<stdin>");
    }
}

int emit_sql(Program *prog, FILE *out, DiagList *diags) {
    (void)diags;

    emit_sql_header(out, prog->filename);

    /* First pass: collect ξ enums for CHECK constraints */
    EnumRegistry er;
    er_init(&er);

    /* Collect from imported programs first */
    size_t imp_count = 0;
    Decl **imp_decls = collect_imported_decls(prog, &imp_count);
    for (size_t i = 0; i < imp_count; i++) {
        Decl *d = imp_decls[i];
        if (d->type == DECL_KINDED_VALUE && d->kind == KIND_XI &&
            d->as.kinded.value && d->as.kinded.value->type == EXPR_ENUM &&
            d->name.text) {
            er_add(&er, d->name.text, d->as.kinded.value);
        }
    }
    free(imp_decls);

    /* Collect from local declarations */
    for (size_t i = 0; i < prog->count; i++) {
        Decl *d = prog->decls[i];
        if (d->type == DECL_KINDED_VALUE && d->kind == KIND_XI &&
            d->as.kinded.value && d->as.kinded.value->type == EXPR_ENUM &&
            d->name.text) {
            er_add(&er, d->name.text, d->as.kinded.value);
        }
    }

    /* M4: set file-scope er for dispatch wrappers */
    g_sql_er = &er;

    /* M4: dispatch via generated switch from ordbok.
     * Replaces hand-written 12-case DeclType switch.
     * Source of truth: ordbok/compiler/compiler_emit_sql_dispatch.szh */
    for (size_t i = 0; i < prog->count; i++) {
        Decl *d = prog->decls[i];
        emit_sql_dispatch(out, d);
    }

    /* Phase 1: emit kind metadata table after all declarations */
    emit_kind_metadata_table(out, prog);

    er_free(&er);
    return 0;
}
