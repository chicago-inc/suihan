/* Pluralize a table name: membership → memberships */
static char *pluralize(const char *name) {
    if (!name) return strdup("unknowns");
    size_t len = strlen(name);
    char *out = malloc(len + 4);

    /* Simple English pluralization heuristics */
    if (len > 1 && name[len-1] == 'y' &&
        name[len-2] != 'a' && name[len-2] != 'e' &&
        name[len-2] != 'o' && name[len-2] != 'u') {
        /* dependency → dependencies */
        memcpy(out, name, len - 1);
        strcpy(out + len - 1, "ies");
    } else if (len > 1 && (name[len-1] == 's' || name[len-1] == 'x' ||
               name[len-1] == 'z' ||
               (len > 2 && name[len-2] == 'c' && name[len-1] == 'h') ||
               (len > 2 && name[len-2] == 's' && name[len-1] == 'h'))) {
        /* match → matches */
        sprintf(out, "%ses", name);
    } else {
        sprintf(out, "%ss", name);
    }
    return out;
}

