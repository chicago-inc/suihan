/* Convert meihua function calls to Math.* equivalents */
static char *meihua_expr_to_ts(Expr *e) {
    if (!e) return strdup("0");

    switch (e->type) {
    case EXPR_CALL: {
        if (!e->as.call.callee) return strdup("0");
        /* Map mathematical functions to Math.* */
        const char *callee = e->as.call.callee;
        const char *math_fn = NULL;
        if (strcmp(callee, "sqrt") == 0) math_fn = "Math.sqrt";
        else if (strcmp(callee, "abs") == 0) math_fn = "Math.abs";
        else if (strcmp(callee, "floor") == 0) math_fn = "Math.floor";
        else if (strcmp(callee, "ceil") == 0) math_fn = "Math.ceil";
        else if (strcmp(callee, "round") == 0) math_fn = "Math.round";
        else if (strcmp(callee, "min") == 0) math_fn = "Math.min";
        else if (strcmp(callee, "max") == 0) math_fn = "Math.max";
        else if (strcmp(callee, "log") == 0) math_fn = "Math.log";
        else if (strcmp(callee, "sin") == 0) math_fn = "Math.sin";
        else if (strcmp(callee, "cos") == 0) math_fn = "Math.cos";
        else if (strcmp(callee, "tan") == 0) math_fn = "Math.tan";
        else if (strcmp(callee, "acos") == 0) math_fn = "Math.acos";
        else if (strcmp(callee, "asin") == 0) math_fn = "Math.asin";
        else if (strcmp(callee, "atan") == 0) math_fn = "Math.atan";
        else if (strcmp(callee, "atan2") == 0) math_fn = "Math.atan2";
        else if (strcmp(callee, "pow") == 0) math_fn = "Math.pow";

        const char *fn = math_fn ? math_fn : callee;
        size_t total_len = strlen(fn) + 3;
        char **arg_strs = malloc(e->as.call.arg_count * sizeof(char *));
        for (size_t i = 0; i < e->as.call.arg_count; i++) {
            arg_strs[i] = meihua_expr_to_ts(e->as.call.args[i]);
            total_len += strlen(arg_strs[i]) + 2;
        }
        char *buf = malloc(total_len + 1);
        int pos = sprintf(buf, "%s(", fn);
        for (size_t i = 0; i < e->as.call.arg_count; i++) {
            if (i > 0) pos += sprintf(buf + pos, ", ");
            pos += sprintf(buf + pos, "%s", arg_strs[i]);
            free(arg_strs[i]);
        }
        sprintf(buf + pos, ")");
        free(arg_strs);
        return buf;
    }
    case EXPR_BINARY: {
        char *left = meihua_expr_to_ts(e->as.binary.left);
        char *right = meihua_expr_to_ts(e->as.binary.right);
        const char *op = e->as.binary.op ? e->as.binary.op : "+";
        if (strcmp(op, "^") == 0) {
            char *buf = malloc(strlen(left) + strlen(right) + 20);
            sprintf(buf, "Math.pow(%s, %s)", left, right);
            free(left); free(right);
            return buf;
        }
        /* TS operator mapping: == → ===, != → !== */
        const char *ts_op = op;
        if (strcmp(op, "==") == 0) ts_op = "===";
        else if (strcmp(op, "!=") == 0) ts_op = "!==";
        char *buf = malloc(strlen(left) + strlen(right) + strlen(ts_op) + 8);
        sprintf(buf, "(%s %s %s)", left, ts_op, right);
        free(left); free(right);
        return buf;
    }
    case EXPR_IDENT:
        if (e->as.ident.name) return strdup(e->as.ident.name);
        return strdup("0");
    case EXPR_NUMBER:
        if (e->as.number.text) return strdup(e->as.number.text);
        return strdup("0");
    case EXPR_UNARY: {
        char *operand = meihua_expr_to_ts(e->as.unary.operand);
        const char *op = e->as.unary.op ? e->as.unary.op : "-";
        char *buf = malloc(strlen(operand) + strlen(op) + 4);
        sprintf(buf, "(%s%s)", op, operand);
        free(operand);
        return buf;
    }
    case EXPR_IF: {
        char *cond = meihua_expr_to_ts(e->as.if_expr.condition);
        char *then_b = meihua_expr_to_ts(e->as.if_expr.then_branch);
        char *else_b = meihua_expr_to_ts(e->as.if_expr.else_branch);
        char *buf = malloc(strlen(cond) + strlen(then_b) + strlen(else_b) + 16);
        sprintf(buf, "(%s) ? %s : %s", cond, then_b, else_b);
        free(cond); free(then_b); free(else_b);
        return buf;
    }
    case EXPR_COALESCE: {
        char *left = meihua_expr_to_ts(e->as.coalesce.left);
        char *right = meihua_expr_to_ts(e->as.coalesce.right);
        char *buf = malloc(strlen(left) + strlen(right) + 8);
        sprintf(buf, "(%s ?? %s)", left, right);
        free(left); free(right);
        return buf;
    }
    case EXPR_STRING: {
        const char *val = e->as.string.value ? e->as.string.value : "";
        char *buf = malloc(strlen(val) + 4);
        sprintf(buf, "'%s'", val);
        return buf;
    }
    case EXPR_LIST: {
        size_t total = 4; /* [] */
        char **items = malloc(e->as.list.count * sizeof(char *));
        for (size_t i = 0; i < e->as.list.count; i++) {
            items[i] = meihua_expr_to_ts(e->as.list.items[i]);
            total += strlen(items[i]) + 2;
        }
        char *buf = malloc(total + 1);
        int pos = sprintf(buf, "[");
        for (size_t i = 0; i < e->as.list.count; i++) {
            if (i > 0) pos += sprintf(buf + pos, ", ");
            pos += sprintf(buf + pos, "%s", items[i]);
            free(items[i]);
        }
        sprintf(buf + pos, "]");
        free(items);
        return buf;
    }
    case EXPR_MATCH: {
        /* match disc { a -> x, b -> y, _ -> z } → nested ternary */
        char *disc = meihua_expr_to_ts(e->as.match_expr.discriminant);
        /* Build from last arm (default) backward */
        char *result = NULL;
        /* Find wildcard arm for default */
        for (size_t i = 0; i < e->as.match_expr.arm_count; i++) {
            Expr *pat = e->as.match_expr.arms[i].pattern;
            if (pat && pat->type == EXPR_WILDCARD) {
                result = meihua_expr_to_ts(e->as.match_expr.arms[i].body);
                break;
            }
        }
        if (!result) result = strdup("undefined");
        /* Wrap non-wildcard arms as ternaries */
        for (int i = (int)e->as.match_expr.arm_count - 1; i >= 0; i--) {
            Expr *pat = e->as.match_expr.arms[i].pattern;
            if (pat && pat->type == EXPR_WILDCARD) continue;
            /* Pattern idents are literal match values — emit as string literals */
            char *pstr;
            if (pat && pat->type == EXPR_IDENT && pat->as.ident.name) {
                pstr = malloc(strlen(pat->as.ident.name) + 4);
                sprintf(pstr, "'%s'", pat->as.ident.name);
            } else {
                pstr = meihua_expr_to_ts(pat);
            }
            char *body = meihua_expr_to_ts(e->as.match_expr.arms[i].body);
            char *new_r = malloc(strlen(disc) + strlen(pstr) + strlen(body) + strlen(result) + 24);
            sprintf(new_r, "(%s === %s) ? %s : %s", disc, pstr, body, result);
            free(pstr); free(body); free(result);
            result = new_r;
        }
        free(disc);
        return result;
    }
    default:
        return expr_to_ts(e);
    }
}

static void emit_meihua(FILE *out, Decl *d) {
    if (!d->name.text) return;
    char *fn_name = to_camel(d->name.text);

    fprintf(out, "/** meihua %s — pure computation (no side effects) */\n",
            d->name.text);
    fprintf(out, "export function %s(", fn_name);

    for (size_t i = 0; i < d->as.exec_layer.param_count; i++) {
        if (d->as.exec_layer.params[i].text) {
            fprintf(out, "%s: number", d->as.exec_layer.params[i].text);
            if (i + 1 < d->as.exec_layer.param_count) fprintf(out, ", ");
        }
    }

    fprintf(out, "): number {\n");

    /* Emit real body if the parser captured one */
    Expr *body = d->as.exec_layer.body;
    /* Unwrap single-statement blocks */
    if (body && body->type == EXPR_BLOCK && body->as.block.count == 1) {
        body = body->as.block.stmts[0];
    }
    if (body) {
        char *ts = meihua_expr_to_ts(body);
        fprintf(out, "  return %s;\n", ts);
        free(ts);
    } else {
        fprintf(out, "  return 0; // no body captured\n");
    }

    fprintf(out, "}\n\n");

    free(fn_name);
}

