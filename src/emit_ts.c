/*
 * suhc — emit_ts.c
 * TypeScript code generation from .szh declarations.
 *
 * Emission rules derived from the kind system (§2):
 *   ξ → const object + type union (immutable)
 *   ζ → pure function (computed at render time, never stored)
 *   x → interface field (mutable runtime data)
 *   R.k → function (traversal operator)
 *   ω → return type (terminal output)
 *   ΔR.k → JSDoc comment (entropy cast documentation)
 *
 * dimension + perpendicular → branded types (dimensional error prevention)
 * dependency → interface (typed relationship)
 * projection → resolver function (ζ-computation)
 * traversal → typed function with equation documentation
 */

#include "emitter.h"
#include "compat.h"
#include <string.h>
#include <stdlib.h>
#include <ctype.h>
#include <stdarg.h>

/* ------------------------------------------------------------ */
/* String utilities                                              */
/* ------------------------------------------------------------ */

/* Convert snake_case to PascalCase: structural_role → StructuralRole */
static char *to_pascal(const char *snake) {
    if (!snake) return strdup("Unknown");
    size_t len = strlen(snake);
    char *out = malloc(len + 1);
    size_t j = 0;
    bool cap_next = true;
    for (size_t i = 0; i < len; i++) {
        if (snake[i] == '_') {
            cap_next = true;
        } else {
            out[j++] = cap_next ? toupper(snake[i]) : snake[i];
            cap_next = false;
        }
    }
    out[j] = '\0';
    return out;
}

/* Convert snake_case to camelCase: structural_role → structuralRole */
static char *to_camel(const char *snake) {
    if (!snake) return strdup("unknown");
    char *pascal = to_pascal(snake);
    if (pascal[0]) pascal[0] = tolower(pascal[0]);
    return pascal;
}

/* Capitalize first letter: owner → Owner */
static char *capitalize(const char *s) {
    if (!s || !*s) return strdup("");
    char *out = strdup(s);
    out[0] = toupper(out[0]);
    return out;
}

