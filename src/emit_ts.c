/* ------------------------------------------------------------ */
/* Kind manifest — preserves kind metadata in TypeScript output  */
/* ------------------------------------------------------------ */

/* ASCII-safe kind identifier for TypeScript (avoids Unicode sigils) */
static const char *kind_id(Kind k) {
    switch (k) {
    case KIND_XI:       return "xi";
    case KIND_ZETA:     return "zeta";
    case KIND_X:        return "x";
    case KIND_RK:       return "rk";
    case KIND_OMEGA:    return "omega";
    case KIND_DELTA_RK: return "delta_rk";
    case KIND_INFERRED: return "inferred";
    case KIND_NONE:     return "none";
    }
    return "unknown";
}

static void emit_kind_manifest(FILE *out, Program *prog) {
    /* Count non-import declarations to decide whether to emit */
    size_t real_count = 0;
    for (size_t i = 0; i < prog->count; i++) {
        if (prog->decls[i]->type != DECL_IMPORT &&
            prog->decls[i]->name.text)
            real_count++;
    }
    if (real_count == 0) return;

    fprintf(out, "\n/* Kind manifest — 256-bit perpendicular encoding metadata */\n");
    fprintf(out, "export const __kindManifest = {\n");

    bool first = true;
    /* De-duplicate by name — relation decls (perpendicular/commensurable) use
     * d->name.text = first dimension name, which collides with the dimension's
     * own entry. */
    char *seen[512] = {0};
    int n_seen = 0;
    for (size_t i = 0; i < prog->count; i++) {
        Decl *d = prog->decls[i];
        if (d->type == DECL_IMPORT) continue;
        if (d->type == DECL_PERPENDICULAR ||
            d->type == DECL_COMMENSURABLE ||
            d->type == DECL_INCOMMENSURABLE) continue;
        if (!d->name.text) continue;
        bool dup = false;
        for (int s = 0; s < n_seen; s++) {
            if (strcmp(seen[s], d->name.text) == 0) { dup = true; break; }
        }
        if (dup) continue;
        if (n_seen < 512) seen[n_seen++] = (char *)d->name.text;
        if (!first) fprintf(out, ",\n");
        fprintf(out, "  '%s': '%s'", d->name.text, kind_id(d->kind));
        first = false;
    }
    fprintf(out, "\n} as const;\n\n");

    fprintf(out, "export type KindOf<K extends keyof typeof __kindManifest>"
                 " = typeof __kindManifest[K];\n");
}

int emit_typescript(Program *prog, FILE *out, DiagList *diags) {
    (void)diags;

    /* M4: set file-scope prog for dispatch wrappers */
    g_ts_prog = prog;

    emit_header(out, prog->filename);

    /* Emit imports first (used-names-only — Sprint 3B) */
    for (size_t i = 0; i < prog->count; i++) {
        if (prog->decls[i]->type == DECL_IMPORT)
            emit_import(out, prog->decls[i], prog);
    }

    /* M4: dispatch via generated switch from ordbok.
     * Replaces hand-written 17-case DeclType switch.
     * Source of truth: ordbok/compiler/compiler_emit_ts_dispatch.szh */
    for (size_t i = 0; i < prog->count; i++) {
        Decl *d = prog->decls[i];
        emit_ts_dispatch(out, d);
    }

    /* Phase 1: emit kind manifest after all declarations */
    emit_kind_manifest(out, prog);

    return 0;
}
