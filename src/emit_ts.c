/* Check if an expression tree references a name (by string match) */
static bool expr_references_name(Expr *e, const char *name) {
    if (!e || !name) return false;
    switch (e->type) {
    case EXPR_IDENT:
        if (e->as.ident.name && strcmp(e->as.ident.name, name) == 0)
            return true;
        break;
    case EXPR_CALL:
        if (e->as.call.callee && strcmp(e->as.call.callee, name) == 0)
            return true;
        for (size_t i = 0; i < e->as.call.arg_count; i++)
            if (expr_references_name(e->as.call.args[i], name)) return true;
        break;
    case EXPR_BINARY:
        if (expr_references_name(e->as.binary.left, name)) return true;
        if (expr_references_name(e->as.binary.right, name)) return true;
        break;
    case EXPR_UNARY:
        if (expr_references_name(e->as.unary.operand, name)) return true;
        break;
    case EXPR_LIST:
        for (size_t i = 0; i < e->as.list.count; i++)
            if (expr_references_name(e->as.list.items[i], name)) return true;
        break;
    case EXPR_BLOCK:
        for (size_t i = 0; i < e->as.block.count; i++)
            if (expr_references_name(e->as.block.stmts[i], name)) return true;
        break;
    case EXPR_ARROW:
        if (expr_references_name(e->as.arrow.from, name)) return true;
        if (expr_references_name(e->as.arrow.to, name)) return true;
        break;
    case EXPR_COALESCE:
        if (expr_references_name(e->as.coalesce.left, name)) return true;
        if (expr_references_name(e->as.coalesce.right, name)) return true;
        break;
    case EXPR_PIPE_CHAIN:
        for (size_t i = 0; i < e->as.pipe_chain.count; i++)
            if (expr_references_name(e->as.pipe_chain.stages[i], name)) return true;
        break;
    case EXPR_IF:
        if (expr_references_name(e->as.if_expr.condition, name)) return true;
        if (expr_references_name(e->as.if_expr.then_branch, name)) return true;
        if (expr_references_name(e->as.if_expr.else_branch, name)) return true;
        break;
    default:
        break;
    }
    return false;
}

/* Check if a local declaration references an imported name.
 * This checks field labels, field values, projection arm patterns/results,
 * dependency entries, etc. Also matches singular/plural variants. */
static bool decl_references_name(Decl *d, const char *name) {
    if (!d || !name) return false;

    /* Check field values and labels */
    switch (d->type) {
    case DECL_PROJECTION:
        for (size_t f = 0; f < d->as.projection.field_count; f++) {
            DeclField *fld = &d->as.projection.fields[f];
            if (fld->value && expr_references_name(fld->value, name))
                return true;
        }
        for (size_t a = 0; a < d->as.projection.arm_count; a++) {
            ProjectionArm *arm = &d->as.projection.arms[a];
            if (expr_references_name(arm->pattern, name)) return true;
            if (expr_references_name(arm->body, name)) return true;
        }
        break;
    case DECL_DEPENDENCY:
        if (expr_references_name(d->as.dependency.relation, name)) return true;
        for (size_t f = 0; f < d->as.dependency.field_count; f++) {
            DeclField *fld = &d->as.dependency.fields[f];
            if (fld->value && expr_references_name(fld->value, name))
                return true;
        }
        break;
    case DECL_KINDED_VALUE:
        if (expr_references_name(d->as.kinded.value, name)) return true;
        break;
    case DECL_TRAVERSAL:
        for (size_t s = 0; s < d->as.traversal.section_count; s++) {
            if (expr_references_name(d->as.traversal.sections[s].body, name))
                return true;
        }
        break;
    case DECL_MEIHUA:
    case DECL_ZHULIN:
    case DECL_SONGQIAO:
        if (expr_references_name(d->as.exec_layer.body, name)) return true;
        break;
    case DECL_MORPHISM:
        if (expr_references_name(d->as.morphism.signature, name)) return true;
        for (size_t f = 0; f < d->as.morphism.field_count; f++) {
            DeclField *fld = &d->as.morphism.fields[f];
            if (fld->value && expr_references_name(fld->value, name))
                return true;
        }
        break;
    default:
        break;
    }
    return false;
}

/* Check if an imported declaration name is referenced by any local decl.
 * Also checks singular/plural variants. */
static bool is_imported_name_used(const char *imp_name, Program *local_prog) {
    for (size_t i = 0; i < local_prog->count; i++) {
        Decl *d = local_prog->decls[i];
        if (d->type == DECL_IMPORT) continue;
        if (decl_references_name(d, imp_name)) return true;
    }

    /* Also try singular/plural variants */
    size_t len = strlen(imp_name);

    /* Try appending 's' */
    char *plural = malloc(len + 2);
    sprintf(plural, "%ss", imp_name);
    for (size_t i = 0; i < local_prog->count; i++) {
        Decl *d = local_prog->decls[i];
        if (d->type == DECL_IMPORT) continue;
        if (decl_references_name(d, plural)) { free(plural); return true; }
    }
    free(plural);

    /* Try stripping trailing 's' */
    if (len > 1 && imp_name[len - 1] == 's') {
        char *singular = strndup(imp_name, len - 1);
        for (size_t i = 0; i < local_prog->count; i++) {
            Decl *d = local_prog->decls[i];
            if (d->type == DECL_IMPORT) continue;
            if (decl_references_name(d, singular)) { free(singular); return true; }
        }
        free(singular);
    }

    return false;
}

/* Emit TypeScript import statement for a resolved DECL_IMPORT.
 * Sprint 3B: only emits actually-used names from the imported module.
 * If no names are used, suppresses the import line entirely. */
static void emit_import(FILE *out, Decl *d, Program *local_prog) {
    if (!d->as.import_decl.resolved) return;

    Program *imported = d->as.import_decl.resolved;
    if (imported->count == 0) return;

    /* First pass: collect only used names */
    char *used[256];
    int n_used = 0;

    for (size_t i = 0; i < imported->count; i++) {
        Decl *id = imported->decls[i];
        if (!id->name.text) continue;
        if (id->type == DECL_IMPORT) continue;

        /* Check if this imported name is actually used locally */
        if (!is_imported_name_used(id->name.text, local_prog)) continue;

        char *name = to_pascal(id->name.text);

        /* Check for duplicates */
        int dup = 0;
        for (int s = 0; s < n_used; s++) {
            if (strcmp(used[s], name) == 0) { dup = 1; break; }
        }
        if (dup) { free(name); continue; }

        if (n_used < 256) used[n_used++] = name;
    }

    /* If no names are used, suppress import entirely */
    if (n_used == 0) return;

    fprintf(out, "import {");
    for (int i = 0; i < n_used; i++) {
        if (i > 0) fprintf(out, ",");
        fprintf(out, " %s", used[i]);
    }
    fprintf(out, " } from './%s';\n", d->as.import_decl.module_name);

    for (int i = 0; i < n_used; i++) free(used[i]);
}

